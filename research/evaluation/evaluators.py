"""LLM-as-a-Judge evaluators with Arize Phoenix Cloud integration.

Defines evaluation functions for each agent in the research framework.
Includes integration with Arize Phoenix Cloud for persistent logging of
evaluation results, metrics, and experiment tracking.

- PlanEvaluator: Evaluates the quality of the research plan generated by the planning agent.
- GatheringEvaluator: Evaluates the quality of sources and information gathered by the gathering agent.
- SynthesisEvaluator: Evaluates the quality of the report synthesized by the synthesis agent.
- VerificationEvaluator: Evaluates the verification accuracy of the verification agent.

"""

from __future__ import annotations

import traceback
from time import perf_counter

import pandas as pd
from openinference.instrumentation import suppress_tracing
from phoenix import Client
from phoenix.evals import llm_classify
from phoenix.evals.models import AnthropicModel
from pydantic import BaseModel, ConfigDict, Field

from research.evaluation.prompts import (
    PLAN_QUALITY_PROMPT,
    REPORT_QUALITY_PROMPT,
    SOURCE_QUALITY_PROMPT,
    VERIFICATION_QUALITY_PROMPT,
)
from research.evaluation.schemas import (
    EvaluationLabel,
    EvaluationResult,
    ExecutionMetadata,
)
from research.models import (
    ResearchPlan,
    ResearchReport,
    SearchResult,
    ValidationResult,
)


class EvaluatorConfig(BaseModel):
    """Runtime configuration for LLM-as-a-Judge evaluators."""

    model_config = ConfigDict(frozen=True)

    model_provider: str = Field(default="anthropic", min_length=1)
    model_name: str = Field(default="claude-sonnet-4-5", min_length=1)
    max_retries: int = Field(default=3, ge=1)
    temperature: float = Field(default=0.0, ge=0.0, le=1.0)
    log_to_arize: bool = Field(default=True)


def get_llm_model(config: EvaluatorConfig) -> AnthropicModel:
    """Initialize and return the LLM model based on the provided config."""
    if config.model_provider == "anthropic":
        return AnthropicModel(
            model=config.model_name,
            temperature=config.temperature,
            top_p=None,  # Exclude top_p to avoid API conflict with temperature
        )
    else:
        raise ValueError(f"Unsupported model provider: {config.model_provider}")


def _log_to_phoenix(eval_name: str, result: EvaluationResult, span_id: str | None) -> None:
    """Log evaluation result to Phoenix Cloud for UI tracking.

    The Client automatically reads PHOENIX_API_KEY and PHOENIX_COLLECTOR_ENDPOINT
    from environment variables for Arize Cloud authentication.

    Failures are silently ignored to avoid crashing the evaluation.
    """
    if span_id is None:
        return

    try:
        from phoenix.client.types import SpanAnnotation

        label = "PASS" if result.label == EvaluationLabel.PASS else "FAIL"
        annotation = SpanAnnotation(
            span_id=span_id,
            name=eval_name,
            annotator_kind="LLM",
            result={"label": label, "explanation": result.explanation},
        )
        Client().spans.log_span_annotations(annotations=[annotation])
    except Exception:
        # Phoenix logging is best-effort; don't crash the evaluation
        pass


def evaluate_plan(
    plan: ResearchPlan,
    query: str,
    test_id: str,
    config: EvaluatorConfig | None = None,
    span_id: str | None = None,
) -> EvaluationResult:
    """Evaluate the quality of a research plan using LLM-as-a-Judge.

    Args:
        plan: The ResearchPlan object to evaluate.
        query: Original research query for context.
        test_id: Unique test identifier for logging.
        config: EvaluatorConfig with model and logging settings.
        span_id: Phoenix span ID for tracing correlation.

    Returns:
        EvaluationResult with PASS/FAIL label and reasoning.
    """
    if config is None:
        config = EvaluatorConfig()
    start_time = perf_counter()
    error_message: str | None = None

    # Prepare the DataFrame for Phoenix llm_classify
    df = pd.DataFrame(
        [
            {
                "query": query,
                "executive_summary": plan.executive_summary,
                "web_search_steps": str(
                    [{"search_terms": step.search_terms, "purpose": step.purpose} for step in plan.web_search_steps]
                ),
                "analysis_instructions": plan.analysis_instructions,
            }
        ]
    )

    try:
        # Run the LLM classification (suppress tracing to keep agent traces clean)
        model = get_llm_model(config)
        with suppress_tracing():
            result_df = llm_classify(
                data=df,
                model=model,
                template=PLAN_QUALITY_PROMPT,
                rails=["PASS", "FAIL"],
                provide_explanation=True,
            )

        # Extract and validate label
        # Note: Phoenix llm_classify returns lowercase labels ("pass", "fail")
        label_str = result_df["label"].iloc[0]
        if pd.isna(label_str) or label_str not in ("pass", "fail"):
            label = EvaluationLabel.FAIL
            error_message = f"LLM returned invalid label: {label_str!r}"
        else:
            label = EvaluationLabel.PASS if label_str == "pass" else EvaluationLabel.FAIL

        # Extract and validate explanation
        raw_explanation = result_df["explanation"].iloc[0]
        if pd.isna(raw_explanation) or not str(raw_explanation).strip():
            explanation = "No explanation provided by the LLM."
        else:
            explanation = str(raw_explanation).strip()[:2000]

    except Exception as e:
        duration_ms = (perf_counter() - start_time) * 1000
        return EvaluationResult(
            test_id=test_id,
            agent_name="planning_agent",
            label=EvaluationLabel.FAIL,
            explanation=f"Evaluation failed: {e}",
            evaluation_type="plan_quality",
            span_id=span_id,
            error_message=str(e),
            stack_trace=traceback.format_exc(),
            execution_metadata=ExecutionMetadata(
                duration_ms=duration_ms,
                model_provider=config.model_provider,
                model_name=config.model_name,
            ),
        )

    duration_ms = (perf_counter() - start_time) * 1000

    result = EvaluationResult(
        test_id=test_id,
        agent_name="planning_agent",
        label=label,
        explanation=explanation,
        evaluation_type="plan_quality",
        span_id=span_id,
        error_message=error_message,
        execution_metadata=ExecutionMetadata(
            duration_ms=duration_ms,
            model_provider=config.model_provider,
            model_name=config.model_name,
        ),
    )

    if config.log_to_arize and span_id:
        _log_to_phoenix("plan_quality", result, span_id)

    return result


